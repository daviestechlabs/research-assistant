const postgresMetadataDDL = `CREATE SCHEMA IF NOT EXISTS research_catalog;
CREATE TABLE IF NOT EXISTS research_catalog.generations(
 id text PRIMARY KEY, source_sha text NOT NULL DEFAULT '', logical_sha text NOT NULL DEFAULT '',
 status text NOT NULL CHECK(status IN ('importing','building','ready')), parent_id text NOT NULL DEFAULT '',
 cursor_row bigint NOT NULL DEFAULT 0, source_rows bigint NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);`

var postgresCopyColumns = []string{"rowid", "id", "source", "title", "authors", "summary", "summary_kind", "categories", "language", "published", "doi", "nas_ref", "fingerprint", "imported_at"}

func postgresCreateTables(ctx context.Context, tx pgx.Tx, schema string) error {
	q := pgx.Identifier{schema}.Sanitize()
	docs := q + ".documents"
	_, e := tx.Exec(ctx, `CREATE SCHEMA `+q+`; CREATE TABLE `+docs+`(
 rowid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id text NOT NULL UNIQUE,
 source text NOT NULL CHECK(source IN ('arxiv','gutenberg')),title text NOT NULL,authors text NOT NULL,
 summary text NOT NULL, summary_kind text NOT NULL CHECK(summary_kind IN ('abstract','catalog-description','missing')),
 categories text NOT NULL,language text NOT NULL,published text NOT NULL,doi text NOT NULL,nas_ref text NOT NULL,
 fingerprint text NOT NULL CHECK(length(fingerprint)=64),imported_at text NOT NULL,
 abstract_search tsvector GENERATED ALWAYS AS(to_tsvector('english',regexp_replace(summary,'\mi\s*/\s*o\M',' input output io ','gi'))) STORED,
 catalog_search tsvector GENERATED ALWAYS AS(setweight(to_tsvector('english',title),'A') || setweight(to_tsvector('english',authors),'B') || setweight(to_tsvector('english',regexp_replace(summary,'\mi\s*/\s*o\M',' input output io ','gi')),'C') || setweight(to_tsvector('english',categories),'B') || setweight(to_tsvector('simple',doi),'A')) STORED,
 category_tags text[] GENERATED ALWAYS AS(string_to_array(categories,' ')) STORED
 );CREATE TABLE `+q+`.catalog_stats(source text PRIMARY KEY,documents bigint NOT NULL,missing_summaries bigint NOT NULL);
 CREATE TABLE `+q+`.indexing_checkpoint(id integer PRIMARY KEY CHECK(id=1),state text NOT NULL);`)
	return e
}
func postgresIndexesAndCounters(ctx context.Context, tx pgx.Tx, schema string) error {
	q := pgx.Identifier{schema}.Sanitize()
	docs := q + ".documents"
	_, e := tx.Exec(ctx, `CREATE INDEX IF NOT EXISTS documents_abstract_gin ON `+docs+` USING gin(abstract_search);
 CREATE INDEX IF NOT EXISTS documents_catalog_gin ON `+docs+` USING gin(catalog_search);
 CREATE INDEX IF NOT EXISTS documents_filter ON `+docs+`(source,published,id);
 CREATE INDEX IF NOT EXISTS documents_doi ON `+docs+`(doi) WHERE doi!='';
 CREATE INDEX IF NOT EXISTS documents_categories ON `+docs+` USING gin(category_tags);
 TRUNCATE `+q+`.catalog_stats; INSERT INTO `+q+`.catalog_stats SELECT source,count(*),sum((summary_kind='missing')::int) FROM `+docs+` GROUP BY source;
 SELECT setval(pg_get_serial_sequence('`+schema+`.documents','rowid'),GREATEST(COALESCE((SELECT max(rowid) FROM `+docs+`),0),1),true);
 CREATE OR REPLACE FUNCTION `+q+`.document_counts() RETURNS trigger LANGUAGE plpgsql AS $body$
 BEGIN
 IF TG_OP IN ('UPDATE','DELETE') THEN UPDATE `+q+`.catalog_stats SET documents=documents-1,missing_summaries=missing_summaries-(OLD.summary_kind='missing')::int WHERE source=OLD.source;END IF;
 IF TG_OP IN ('INSERT','UPDATE') THEN INSERT INTO `+q+`.catalog_stats AS counters VALUES(NEW.source,1,(NEW.summary_kind='missing')::int) ON CONFLICT(source) DO UPDATE SET documents=counters.documents+1,missing_summaries=counters.missing_summaries+EXCLUDED.missing_summaries;END IF;
 RETURN NULL;END $body$;
 DROP TRIGGER IF EXISTS document_counts ON `+docs+`; CREATE TRIGGER document_counts AFTER INSERT OR UPDATE OR DELETE ON `+docs+` FOR EACH ROW EXECUTE FUNCTION `+q+`.document_counts();
 CREATE OR REPLACE FUNCTION `+q+`.assert_building() RETURNS trigger LANGUAGE plpgsql AS $guard$
 DECLARE phase text; BEGIN
 SELECT status INTO phase FROM research_catalog.generations WHERE id='`+strings.TrimPrefix(schema, "research_g_")+`' FOR SHARE;
 IF phase IS NULL OR phase NOT IN ('importing','building') THEN RAISE EXCEPTION 'catalog generation is immutable' USING ERRCODE='55000';END IF;
 IF TG_OP='DELETE' THEN RETURN OLD;ELSE RETURN NEW;END IF;END $guard$;
 DROP TRIGGER IF EXISTS generation_immutable ON `+docs+`; CREATE TRIGGER generation_immutable BEFORE INSERT OR UPDATE OR DELETE ON `+docs+` FOR EACH ROW EXECUTE FUNCTION `+q+`.assert_building();
 DROP TRIGGER IF EXISTS generation_immutable ON `+q+`.catalog_stats; CREATE TRIGGER generation_immutable BEFORE INSERT OR UPDATE OR DELETE ON `+q+`.catalog_stats FOR EACH ROW EXECUTE FUNCTION `+q+`.assert_building();
 DROP TRIGGER IF EXISTS generation_immutable_truncate ON `+docs+`; CREATE TRIGGER generation_immutable_truncate BEFORE TRUNCATE ON `+docs+` FOR EACH STATEMENT EXECUTE FUNCTION `+q+`.assert_building();
 DROP TRIGGER IF EXISTS generation_immutable_truncate ON `+q+`.catalog_stats; CREATE TRIGGER generation_immutable_truncate BEFORE TRUNCATE ON `+q+`.catalog_stats FOR EACH STATEMENT EXECUTE FUNCTION `+q+`.assert_building();`)
	if e != nil {
		return e
	}
	var reader bool
	if e = tx.QueryRow(ctx, "SELECT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='desk_reader')").Scan(&reader); e != nil {
		return e
	}
	if reader {
		_, e = tx.Exec(ctx, "GRANT USAGE ON SCHEMA "+q+" TO desk_reader; GRANT SELECT ON ALL TABLES IN SCHEMA "+q+" TO desk_reader;")
	}
	return e
}
func postgresNewGeneration(ctx context.Context, pool *pgxpool.Pool, id, parent, status, sourceSHA string) (bool, error) {
	schema, e := postgresGenerationSchema(id)
	if e != nil {
		return false, e
	}
	tx, e := pool.Begin(ctx)
	if e != nil {
		return false, e
	}
	defer tx.Rollback(ctx)
	if _, e = tx.Exec(ctx, postgresMetadataDDL); e != nil {
		return false, e
	}
	if _, e = tx.Exec(ctx, "SELECT pg_advisory_xact_lock(hashtext($1))", "research-generation:"+id); e != nil {
		return false, e
	}
	var existing string
	e = tx.QueryRow(ctx, "SELECT status FROM research_catalog.generations WHERE id=$1", id).Scan(&existing)
	if e == nil {
		return false, tx.Commit(ctx)
	}
	if !errors.Is(e, pgx.ErrNoRows) {
		return false, e
	}
	if e = postgresCreateTables(ctx, tx, schema); e != nil {
		return false, e
	}
	if _, e = tx.Exec(ctx, "INSERT INTO research_catalog.generations(id,parent_id,status,source_sha,cursor_row) VALUES($1,$2,$3,$4,CASE WHEN $3='building' THEN -1 ELSE 0 END)", id, parent, status, sourceSHA); e != nil {
		return false, e
	}
	if e = tx.Commit(ctx); e != nil {
		return false, e
	}
	return true, nil
}
func postgresMigrateGeneration(ctx context.Context, g indexGeneration, progress func(map[string]any)) error {
	schema, e := postgresGenerationSchema(g.ID)
	if e != nil {
		return e
	}
	pool, e := postgresPool(ctx)
	if e != nil {
		return e
	}
	defer pool.Close()
	// A matching ready generation is immutable and can be reused by later activation.
	if _, e = pool.Exec(ctx, postgresMetadataDDL); e != nil {
		return errors.New("PostgreSQL registry initialization failed")
	}
	var sourceSHA, status string
	var cursor int64
	e = pool.QueryRow(ctx, "SELECT source_sha,status,cursor_row FROM research_catalog.generations WHERE id=$1", g.ID).Scan(&sourceSHA, &status, &cursor)
	if e == nil {
		if sourceSHA != g.SHA {
			return errors.New("PostgreSQL generation source identity changed")
		}
		if status == "ready" {
			p := &postgresCatalog{pool: pool, schema: schema, id: g.ID}
			logical, e := p.digest(ctx)
			if e != nil {
				return e
			}
			var stored string
			if pool.QueryRow(ctx, "SELECT logical_sha FROM research_catalog.generations WHERE id=$1", g.ID).Scan(&stored) != nil || logical != stored {
				return errors.New("PostgreSQL imported generation content changed")
			}
			return nil
		}
	} else if !errors.Is(e, pgx.ErrNoRows) {
		return errors.New("PostgreSQL generation lookup failed")
	}
	if progress != nil {
		progress(map[string]any{"generation": g.ID, "phase": "source-checksum"})
	}
	sha, e := indexRawFileSHA(g.Catalog)
	if e != nil || sha != g.SHA {
		return errors.New("migration source checksum failed")
	}
	source, e := openSQLiteSource(g.Catalog)
	if e != nil {
		return e
	}
	defer source.close()
	counts, e := source.rows("SELECT count(*) FROM documents")
	if e != nil || len(counts) != 1 {
		return errors.New("migration source counts are unavailable")
	}
	total, _ := strconv.ParseInt(counts[0][0], 10, 64)
	if _, e = postgresNewGeneration(ctx, pool, g.ID, g.Parent, "importing", g.SHA); e != nil {
		return errors.New("PostgreSQL generation creation failed")
	}
	cols := strings.Join(postgresCopyColumns, ",")
	for {
		if e = ctx.Err(); e != nil {
			return e
		}
		rows, err := source.rows("SELECT "+cols+" FROM documents WHERE rowid>? ORDER BY rowid LIMIT 1000", strconv.FormatInt(cursor, 10))
		if err != nil {
			return err
		}
		if len(rows) == 0 {
			break
		}
		tx, err := pool.Begin(ctx)
		if err != nil {
			return err
		}
		values := make([][]any, len(rows))
		next := cursor
		for i, r := range rows {
			n, err := strconv.ParseInt(r[0], 10, 64)
			if err != nil {
				tx.Rollback(ctx)
				return err
			}
			next = n
			v := make([]any, len(r))
			v[0] = n
			for j := 1; j < len(r); j++ {
				v[j] = r[j]
			}
			values[i] = v
		}
		if _, err = tx.CopyFrom(ctx, pgx.Identifier{schema, "documents"}, postgresCopyColumns, pgx.CopyFromRows(values)); err == nil {
			_, err = tx.Exec(ctx, "UPDATE research_catalog.generations SET cursor_row=$2,source_rows=$3,updated_at=now() WHERE id=$1 AND status='importing'", g.ID, next, total)
		}
		if err != nil {
			tx.Rollback(ctx)
			return errors.New("PostgreSQL migration batch failed")
		}
		if err = tx.Commit(ctx); err != nil {
			return errors.New("PostgreSQL migration commit failed")
		}
		cursor = next
		if progress != nil {
			progress(map[string]any{"generation": g.ID, "phase": "copy", "last_row": cursor, "source_records": total})
		}
	}
	if progress != nil {
		progress(map[string]any{"generation": g.ID, "phase": "indexes", "source_records": total})
	}
	tx, e := pool.Begin(ctx)
	if e != nil {
		return e
	}
	defer tx.Rollback(ctx)
	if e = postgresIndexesAndCounters(ctx, tx, schema); e != nil {
		return errors.New("PostgreSQL catalog indexes failed")
	}
	if e = tx.Commit(ctx); e != nil {
		return e
	}
	p := &postgresCatalog{pool: pool, schema: schema, id: g.ID}
	actual, e := p.rows("SELECT count(*) FROM documents")
	if e != nil || actual[0][0] != counts[0][0] {
		return errors.New("PostgreSQL migration count did not reconcile")
	}
	logical, e := p.digest(ctx)
	if e != nil {
		return e
	}
	expected, e := sqliteCatalogDigest(source)
	if e != nil || logical != expected {
		return errors.New("PostgreSQL migration content digest did not reconcile")
	}
	after, e := indexRawFileSHA(g.Catalog)
	if e != nil || after != g.SHA {
		return errors.New("migration source changed")
	}
	if _, e = pool.Exec(ctx, "UPDATE research_catalog.generations SET logical_sha=$2,status='ready',updated_at=now() WHERE id=$1", g.ID, logical); e != nil {
		return errors.New("PostgreSQL migration seal failed")
	}
	if progress != nil {
		progress(map[string]any{"generation": g.ID, "phase": "ready", "records": total, "source_sha256": g.SHA, "logical_sha256": logical})
	}
	return nil
}
func sqliteCatalogDigest(d *database) (string, error) {
	h := sha256.New()
	encoder := json.NewEncoder(h)
	var cursor int64
	for {
		rows, e := d.rows("SELECT "+strings.Join(postgresCopyColumns, ",")+" FROM documents WHERE rowid>? ORDER BY rowid LIMIT 1000", strconv.FormatInt(cursor, 10))
		if e != nil {
			return "", e
		}
		if len(rows) == 0 {
			break
		}
		for _, r := range rows {
			if e = encoder.Encode(r); e != nil {
				return "", e
			}
			cursor, _ = strconv.ParseInt(r[0], 10, 64)
		}
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}
func (p *postgresCatalog) identity(ctx context.Context) (string, error) {
	var source, logical, status string
	if p.pool.QueryRow(ctx, "SELECT source_sha,logical_sha,status FROM research_catalog.generations WHERE id=$1", p.id).Scan(&source, &logical, &status) != nil {
		return "", errors.New("PostgreSQL generation receipt is unavailable")
	}
	if status == "ready" {
		if !shaPattern.MatchString(source) || !shaPattern.MatchString(logical) {
			return "", errors.New("PostgreSQL generation seal is invalid")
		}
		return source, nil
	}
	return p.digest(ctx)
}
func (m *indexManager) preparePostgresCandidate(ctx context.Context, run indexRun, s *indexState, path string, collections []indexCollection) error {
	if _, e := os.Stat(path); e == nil {
		return nil
	} else if !os.IsNotExist(e) {
		return e
	}
	pool, e := postgresPool(ctx)
	if e != nil {
		return e
	}
	defer pool.Close()
	baseSchema, e := postgresGenerationSchema(run.Base.ID)
	if e != nil {
		return e
	}
	schema, e := postgresGenerationSchema(run.ID)
	if e != nil {
		return e
	}
	var baseStatus string
	if pool.QueryRow(ctx, "SELECT status FROM research_catalog.generations WHERE id=$1", run.Base.ID).Scan(&baseStatus) != nil || baseStatus != "ready" {
		return errors.New("PostgreSQL baseline is not ready")
	}
	created, e := postgresNewGeneration(ctx, pool, run.ID, run.Base.ID, "building", "")
	if e != nil {
		return e
	}
	var cloneCursor int64
	if e = pool.QueryRow(ctx, "SELECT cursor_row FROM research_catalog.generations WHERE id=$1", run.ID).Scan(&cloneCursor); e != nil {
		return e
	}
	if created || cloneCursor < 0 {
		tx, e := pool.Begin(ctx)
		if e != nil {
			return e
		}
		defer tx.Rollback(ctx)
		cols := strings.Join(postgresCopyColumns, ",")
		if _, e = tx.Exec(ctx, "INSERT INTO "+pgx.Identifier{schema, "documents"}.Sanitize()+"("+cols+") SELECT "+cols+" FROM "+pgx.Identifier{baseSchema, "documents"}.Sanitize()); e != nil {
			return errors.New("PostgreSQL candidate clone failed")
		}
		if e = postgresIndexesAndCounters(ctx, tx, schema); e != nil {
			return e
		}
		for _, c := range collections {
			if _, e = tx.Exec(ctx, "DELETE FROM "+pgx.Identifier{schema, "documents"}.Sanitize()+" WHERE source=$1", c.Source); e != nil {
				return e
			}
		}
		if _, e = tx.Exec(ctx, "UPDATE research_catalog.generations SET cursor_row=0 WHERE id=$1", run.ID); e != nil {
			return e
		}
		if e = tx.Commit(ctx); e != nil {
			return e
		}
	}
	marker := map[string]any{"storage": "postgres", "generation": run.ID, "schema": schema}
	if e = writeIndexJSON(path, marker); e != nil {
		return e
	}
	s.BaselineSHA = run.Base.SHA
	s.Phase = "keyword"
	d, e := openPostgresCatalog(path, run.ID)
	if e != nil {
		return e
	}
	defer d.close()
	return m.checkpoint(d, s)
}
func postgresSeal(ctx context.Context, g indexGeneration) error {
	d, e := openPostgresCatalogMode(g.Catalog, g.ID, true)
	if e != nil {
		return e
	}
	defer d.close()
	tx, e := d.pg.pool.Begin(ctx)
	if e != nil {
		return e
	}
	defer tx.Rollback(ctx)
	var source, stored, status string
	if tx.QueryRow(ctx, "SELECT source_sha,logical_sha,status FROM research_catalog.generations WHERE id=$1 FOR UPDATE", g.ID).Scan(&source, &stored, &status) != nil {
		return errors.New("PostgreSQL seal identity is unavailable")
	}
	logical, e := d.pg.digest(ctx)
	if e != nil {
		return e
	}
	if status == "ready" {
		if logical != stored || source != g.SHA {
			return errors.New("PostgreSQL identity does not match activation")
		}
		return tx.Commit(ctx)
	}
	if status != "building" || logical != g.SHA {
		return errors.New("PostgreSQL candidate digest changed")
	}
	if _, e = tx.Exec(ctx, "UPDATE research_catalog.generations SET source_sha=$2,logical_sha=$3,status='ready',updated_at=now() WHERE id=$1 AND status='building'", g.ID, g.SHA, logical); e != nil {
		return e
	}
	return tx.Commit(ctx)
}
func migratePostgresCLI() error {
	if !postgresEnabled() {
		return errors.New("PostgreSQL migration needs an explicit pool configuration")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 6*time.Hour)
	defer cancel()
	root := os.Getenv("RESEARCH_INDEX_ROOT")
	var active indexActive
	if readIndexJSON(filepath.Join(root, "active.json"), &active) != nil {
		return errors.New("active catalog receipt is unavailable")
	}
	generations := []indexGeneration{active.Current}
	if active.Previous != nil {
		generations = append(generations, *active.Previous)
	}
	states, _ := os.ReadDir(filepath.Join(root, "runs"))
	for _, entry := range states {
		if !entry.IsDir() {
			continue
		}
		var state indexState
		if readIndexJSON(filepath.Join(root, "runs", entry.Name(), "state.json"), &state) == nil && state.Candidate != nil && (state.Status == "running" || state.Status == "ready") && (state.Phase == "meaning" || state.Phase == "validated") {
			found := false
			for _, g := range generations {
				if g.ID == state.ID {
					found = true
				}
			}
			if !found {
				generations = append(generations, *state.Candidate)
			}
		}
	}

	for _, g := range generations {
		if e := postgresMigrateGeneration(ctx, g, func(v map[string]any) { b, _ := json.Marshal(v); fmt.Println(string(b)) }); e != nil {
			return e
		}
	}
	return nil
}

func (p *postgresCatalog) verify(stage func(string)) error {
	if stage != nil {
		stage("postgres-constraints")
	}
	r, e := p.rows("SELECT count(*) FROM documents WHERE id='' OR title='' OR length(fingerprint)!=64 OR (summary='' AND summary_kind!='missing') OR (summary!='' AND source='arxiv' AND summary_kind!='abstract') OR (summary!='' AND source='gutenberg' AND summary_kind!='catalog-description') OR summary_kind NOT IN ('abstract','catalog-description','missing')")
	if e != nil || len(r) != 1 || r[0][0] != "0" {
		return errors.New("PostgreSQL metadata constraints did not pass")
	}
	if stage != nil {
		stage("postgres-indexes")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	var invalid, total int
	e = p.pool.QueryRow(ctx, "SELECT count(*) FILTER(WHERE NOT i.indisvalid OR NOT i.indisready),count(*) FROM pg_index i JOIN pg_class t ON i.indrelid=t.oid JOIN pg_namespace n ON t.relnamespace=n.oid WHERE n.nspname=$1 AND t.relname='documents'", p.schema).Scan(&invalid, &total)
	if e != nil || invalid != 0 || total < 7 {
		return errors.New("PostgreSQL catalog indexes are not ready")
	}
	p.ticks.Add(1)
	return nil
}
func postgresPrepareActivation(ctx context.Context, g indexGeneration) error {
	var marker struct {
		Storage    string `json:"storage"`
		Generation string `json:"generation"`
	}
	if readIndexJSON(g.Catalog, &marker) == nil && marker.Storage == "postgres" {
		if marker.Generation != g.ID {
			return errors.New("PostgreSQL marker identity changed")
		}
		return postgresSeal(ctx, g)
	}
	return postgresMigrateGeneration(ctx, g, nil)
}

func postgresGenerationAbsent(ctx context.Context, id string) (bool, error) {
	pool, e := postgresPool(ctx)
	if e != nil {
		return false, e
	}
	defer pool.Close()
	var exists bool
	if e = pool.QueryRow(ctx, "SELECT EXISTS(SELECT 1 FROM research_catalog.generations WHERE id=$1)", id).Scan(&exists); e != nil {
		return false, e
	}
	return !exists, nil
}
func postgresRetireGeneration(ctx context.Context, g indexGeneration) error {
	schema, e := postgresGenerationSchema(g.ID)
	if e != nil {
		return e
	}
	pool, e := postgresPool(ctx)
	if e != nil {
		return e
	}
	defer pool.Close()
	tx, e := pool.Begin(ctx)
	if e != nil {
		return e
	}
	defer tx.Rollback(ctx)
	if _, e = tx.Exec(ctx, "SELECT pg_advisory_xact_lock(hashtext($1))", "research-generation:"+g.ID); e != nil {
		return e
	}
	var sha, status string
	e = tx.QueryRow(ctx, "SELECT source_sha,status FROM research_catalog.generations WHERE id=$1 FOR UPDATE", g.ID).Scan(&sha, &status)
	if errors.Is(e, pgx.ErrNoRows) {
		return nil
	}
	if e != nil {
		return e
	}
	if sha != g.SHA || status != "ready" {
		return errors.New("PostgreSQL retirement ownership changed")
	}
	if _, e = tx.Exec(ctx, "DROP SCHEMA "+pgx.Identifier{schema}.Sanitize()+" CASCADE"); e != nil {
		return e
	}
	if _, e = tx.Exec(ctx, "DELETE FROM research_catalog.generations WHERE id=$1", g.ID); e != nil {
		return e
	}
	return tx.Commit(ctx)
}
func postgresPruningIdentity(ctx context.Context, g indexGeneration, pruning bool) (string, error) {
	if !pruning {
		return indexFileSHA(g.Catalog)
	}
	absent, e := postgresGenerationAbsent(ctx, g.ID)
	if e != nil {
		return "", e
	}
	if !absent {
		return indexFileSHA(g.Catalog)
	}
	var marker struct {
		Storage    string `json:"storage"`
		Generation string `json:"generation"`
	}
	if readIndexJSON(g.Catalog, &marker) == nil && marker.Storage == "postgres" && marker.Generation == g.ID {
		return g.SHA, nil
	}
	return indexRawFileSHA(g.Catalog)
}
